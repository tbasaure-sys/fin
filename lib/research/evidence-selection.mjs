import {retrieve} from './filing-engine.mjs';

// Research coverage, not a score of economic attractiveness. Each role retains
// its selection reason and absence; a keyword match never certifies a conclusion.
const ROLES = {
  business: ['business_overview', 'current_performance', 'segment_economics'],
  cash: ['cash_flow_statement', 'cash_explanation', 'capital_obligations'],
  thesis: ['operating_risks', 'financial_risks', 'competitive_risks'],
};
function eligible(c) {
  return c.kind === 'table' ? c.table?.complete === true : c.text.length >= 100;
}
const profitMovement=/(?:gross (?:margin|profit)|operating (?:income|profit))[^.\n]{0,70}\b(?:increased|decreased|declined|improved|was flat|were flat)\b/i;
function rolePriority(role, c) {
  if (role === 'current_performance') return Number(profitMovement.test(c.text) && /due to|driven by|because|reflect|offset/i.test(c.text));
  if (role.endsWith('_risks')) return Number(c.documentSection === '1a');
  if (role === 'capital_obligations') return Number(/^(?:term debt|long.term debt|liquidity and capital resources|material cash requirements|capital expenditures?)\s*$/im.test(c.text));
  return 0;
}
function match(role, c, source) {
  const text = c.text;
  const prose = c.kind === 'prose';
  switch (role) {
    case 'business_overview': return prose && source?.form === '10-K' && c.documentSection === '1';
    case 'current_performance': return prose && ['2','7'].includes(c.documentSection) &&
      (profitMovement.test(text)||/(?:revenue|net sales|operating income)[\s\S]{0,100}(?:increased|decreased|grew|declined)|(?:increase|decrease|growth|decline) in (?:revenue|net sales|operating income)/i.test(text));
    case 'segment_economics': return /reportable segments|operating segments|segment (?:revenue|profit|operating income)/i.test(text)
      ||c.kind==='table'&&/disaggregated (?:net sales|revenues?)|(?:net sales|revenues?) by (?:categor(?:y|ies)|products?|services?)/i.test(text);
    case 'cash_flow_statement': return c.kind === 'table' && /statements? of cash flows|cash flows statements/i.test(text);
    case 'cash_explanation': return prose &&
      /cash (?:from operations|(?:provided by|generated by|used in) (?:operating|investing|financing) activities)[\s\S]{0,100}(?:increased|decreased|due to)|(?:increase|decrease) in (?:cash from operations|operating cash)/i.test(text);
    case 'capital_obligations': return prose && /debt|capital expenditures?|repurchase|lease/i.test(text) && /maturit|obligations|commitment|covenant|capital expenditures?/i.test(text);
    case 'operating_risks': return prose && /risk|could|may|uncertain/i.test(text) && /inventor|manufactur|supplier|demand|obsolescen/i.test(text);
    case 'financial_risks': return prose && /risk|could|may|uncertain/i.test(text) && /liquidity|covenant|credit risk|debt|interest rates/i.test(text);
    case 'competitive_risks': return prose && /risk|could|may|uncertain/i.test(text) && /competit|regulat|antitrust|pricing pressure/i.test(text);
    default: return false;
  }
}

export function selectEvidence(chunks, sources, topic) {
  const sourceMap = new Map(sources.map(s => [s.id, s]));
  const usable = chunks.filter(eligible);
  const extracts = [], roles = [];
  let chars = 0;
  const add = c => {
    if (extracts.some(e => e.id === c.id)) return true;
    if (extracts.length === 3 || chars + c.text.length > 6000) return false;
    extracts.push(c); chars += c.text.length; return true;
  };
  for (const role of ROLES[topic.id]) {
    const candidates = usable.filter(c => match(role, c, sourceMap.get(c.id.split(':')[0])));
    candidates.sort((a,b) => {
      const sa = sourceMap.get(a.id.split(':')[0]), sb = sourceMap.get(b.id.split(':')[0]);
      // Explain the latest operating period, not a more convenient old profit
      // story. Within that filing, earnings drivers complement the sales table.
      const recency=Date.parse(sb.acceptedAt)-Date.parse(sa.acceptedAt);
      if(role==='current_performance'&&recency)return recency;
      return rolePriority(role,b) - rolePriority(role,a) ||
        recency ||
        a.blockStart - b.blockStart || a.id.localeCompare(b.id);
    });
    const chosen = candidates.find(c => add(c));
    roles.push({id: role, status: chosen ? 'selected' : candidates.length ? 'budget_limited' : 'not_identified',
      chunkId: chosen?.id ?? null});
  }
  // Remaining slots can carry useful thematic evidence, but never silently fill
  // a missing role. The coverage contract continues to show what was not found.
  for (const c of retrieve(usable, topic)) add(c);
  return {extracts, coverage: {policy: 'economic-roles-v3', roles,
    excludedIncompleteTables: chunks.filter(c => c.kind === 'table' && c.table?.complete !== true).length,
    excludedOversizedChunks: usable.filter(c => c.text.length > 6000).length,
    characters: chars, completeEconomicAssessment: false}};
}
